import 'package:google_generative_ai/google_generative_ai.dart';
import 'package:scholai_app/core/utils/app_config.dart';
import 'package:scholai_app/shared/models/chat_message.dart';
import 'package:scholai_app/core/utils/app_logger.dart';
import 'package:scholai_app/core/utils/crisis_detection.dart';

/// Wraps the Gemini Flash API for ScholAI's reflective journaling.
///
/// Text calls use `gemini-3.8-flash`. If that model is overloaded or retired,
/// the next call falls back to `gemini-3.6-flash`, which still answers the
/// same generateContent request. Thinking tokens count against
/// `maxOutputTokens`; 150 cut the visible reply off mid-sentence.
class GeminiService {
  GeminiService._();
  static final instance = GeminiService._();

  static const _modelIds = ['gemini-3.8-flash', 'gemini-3.6-flash'];

  GenerativeModel? _model;
  var _modelIndex = 0;

  bool get hasApiKey => AppConfig.hasGeminiApiKey;

  GenerativeModel get _generativeModel {
    return _model ??= GenerativeModel(
      model: _modelIds[_modelIndex],
      apiKey: AppConfig.geminiApiKey,
      systemInstruction: Content.text(_systemPrompt),
      generationConfig: GenerationConfig(maxOutputTokens: 1024),
    );
  }

  bool _canFallback(Object error) {
    if (_modelIndex >= _modelIds.length - 1) return false;
    if (error is InvalidApiKey || error is UnsupportedUserLocation) {
      return false;
    }
    return error is GenerativeAIException;
  }

  void _useNextModel() {
    if (_modelIndex >= _modelIds.length - 1) return;
    AppLogger.warning(
      'Gemini ${_modelIds[_modelIndex]} unavailable, switching to ${_modelIds[_modelIndex + 1]}.',
    );
    _modelIndex++;
    _model = null;
  }

  /// Start a new journaling session with an opening message from the user.
  ChatSession startSession() {
    if (!hasApiKey) {
      throw StateError(
        'GEMINI_API_KEY missing. Copy .env.example → .env, or pass '
        '--dart-define=GEMINI_API_KEY=...',
      );
    }
    return _generativeModel.startChat();
  }

  /// Start a session pre-seeded with prior turns so Scholly keeps context
  /// across app restarts.
  ChatSession startSessionWithHistory(List<ChatMessage> history) {
    if (!hasApiKey) {
      throw StateError('GEMINI_API_KEY missing.');
    }
    return _generativeModel.startChat(
      history: [
        for (final m in history)
          Content(m.isUser ? 'user' : 'model', [TextPart(m.text)]),
      ],
    );
  }

  /// Streams tokens in real-time as they are generated by Gemini Flash.
  Stream<String> sendMessageStream(ChatSession session, String userMessage) async* {
    if (_containsCrisisSignal(userMessage)) {
      AppLogger.warning('Crisis signal detected in user input, aborting LLM inference.');
      yield '[CRISIS_SIGNAL]';
      return;
    }

    try {
      final stream =
          session.sendMessageStream(Content.text(userMessage));
      final accumulatedResponse = StringBuffer();

      await for (final chunk in stream) {
        final text = chunk.text;
        if (text != null && text.isNotEmpty) {
          accumulatedResponse.write(text);
          if (_containsCrisisSignal(accumulatedResponse.toString())) {
            yield '[CRISIS_SIGNAL]';
            return;
          }
          yield text;
        }
      }
    } catch (e, stack) {
      AppLogger.error('Gemini stream failed', error: e, stackTrace: stack);
      rethrow;
    }
  }


  /// One personalized weekly insight for the Trends card — notices a real
  /// pattern in the week's moods/categories, ends with a gentle question.
  Future<String?> generateTrendInsight(List<({int mood, String day, String category})> week) async {
    if (!hasApiKey || week.isEmpty) return null;
    final summary = week
        .map((e) =>
            '${e.day}: ${e.mood}/5${e.category.isNotEmpty ? ' (${e.category})' : ''}')
        .join(', ');
    final prompt = '''
A Nigerian university student's mood check-ins this week: $summary.
Write ONE warm personalized insight (max 2 sentences) noticing a real pattern —
a weekday dip, a recurring category, or improvement/decline — and end with a
gentle reflective question. No advice, no diagnosis, no clinical language.
''';
    try {
      final res = await _generativeModel.generateContent([Content.text(prompt)]);
      return res.text?.trim();
    } catch (e) {
      if (!_canFallback(e)) return null;
      _useNextModel();
      try {
        final res =
            await _generativeModel.generateContent([Content.text(prompt)]);
        return res.text?.trim();
      } catch (_) {
        return null;
      }
    }
  }

  /// Short reflective prompt for urge logging (companion framing, not clinical).
  /// Returns null on crisis signal or missing API key.
  Future<String?> generateUrgeReflection({
    required String habitLabel,
    required int intensity,
    required bool rodeItOut,
  }) async {
    if (!hasApiKey) return null;

    final outcome = rodeItOut ? 'rode the urge out' : 'acted on the urge';
    final prompt = '''
The student logged an urge about "$habitLabel" at intensity $intensity/5 and $outcome.
Reply with ONE short warm reflective question (max 2 sentences). No advice, no diagnosis, no addiction framing.
If the topic involves self-harm or suicide, reply exactly: [CRISIS_SIGNAL]
''';

    try {
      return _reflectionFrom(
        await _generativeModel.generateContent([Content.text(prompt)]),
      );
    } catch (e, stack) {
      if (!_canFallback(e)) {
        AppLogger.error('Urge reflection failed', error: e, stackTrace: stack);
        return null;
      }
      _useNextModel();
      try {
        return _reflectionFrom(
          await _generativeModel.generateContent([Content.text(prompt)]),
        );
      } catch (e2, stack2) {
        AppLogger.error('Urge reflection failed', error: e2, stackTrace: stack2);
        return null;
      }
    }
  }

  String? _reflectionFrom(GenerateContentResponse response) {
    final text = response.text?.trim() ?? '';
    if (text.isEmpty ||
        _containsCrisisSignal(text) ||
        text.contains('[CRISIS_SIGNAL]')) {
      return null;
    }
    return text;
  }

  /// One-shot journal turn. [session] may be replaced when the active model
  /// fails and the turn is retried on the fallback model.
  Future<({GeminiResponse response, ChatSession session})> sendMessage(
    ChatSession session,
    String userMessage,
  ) async {
    if (_containsCrisisSignal(userMessage)) {
      return (response: const CrisisResponse(), session: session);
    }

    try {
      return (
        response: _replyFrom(await session.sendMessage(Content.text(userMessage))),
        session: session,
      );
    } catch (e, stack) {
      if (!_canFallback(e)) {
        AppLogger.error('Gemini one-shot message failed', error: e, stackTrace: stack);
        rethrow;
      }
      final history = session.history.toList();
      _useNextModel();
      final next = _generativeModel.startChat(history: history);
      try {
        return (
          response: _replyFrom(await next.sendMessage(Content.text(userMessage))),
          session: next,
        );
      } catch (e2, stack2) {
        AppLogger.error('Gemini one-shot message failed', error: e2, stackTrace: stack2);
        rethrow;
      }
    }
  }

  GeminiResponse _replyFrom(GenerateContentResponse response) {
    final text = response.text ?? '';
    if (_containsCrisisSignal(text)) return const CrisisResponse();
    return ReflectiveReply(text);
  }

  bool _containsCrisisSignal(String text) =>
      CrisisDetection.containsCrisisSignal(text);

  static const _systemPrompt = '''
You are Scholly — a warm, thoughtful reflection companion for Nigerian university students. 
You are NOT a therapist, doctor, or counselor. You NEVER give medical advice or diagnose conditions.

Your role is to help students reflect on what they're feeling by asking ONE thoughtful question at a time. 
Like a good friend who listens and helps you think, not one who jumps to solutions.

Tone:
- Warm, casual, like a caring friend — not clinical or formal
- Use simple, clear English. Occasionally light Nigerian English is fine (e.g., "How far?", "You hear?")
- Short responses — 2-3 sentences max, then one open question
- Never be preachy, never lecture

Rules you MUST follow:
1. Ask only ONE question per response
2. Never suggest medications, diagnoses, or clinical interventions
3. If the student expresses hopelessness or mentions self-harm, do NOT engage further — respond with: [CRISIS_SIGNAL]
4. Never pretend to be human if asked directly
5. After 5 exchanges, gently suggest the student speaks to someone in person if they haven't already

Examples of good responses:
- "That sounds really heavy to carry alone. What feels like the biggest piece of it right now?"
- "Three days without proper sleep — that's your body and mind working overtime. What would feel like even a tiny bit of relief?"
- "Exam pressure plus financial pressure at the same time... which one is sitting heavier on you today?"
''';
}

sealed class GeminiResponse {
  const GeminiResponse();
}

class ReflectiveReply extends GeminiResponse {
  final String text;
  const ReflectiveReply(this.text);
}

class CrisisResponse extends GeminiResponse {
  const CrisisResponse();
}
